const PREFIX = "locales.portfolioInsights.PORTFOLIO_INSIGHTS_TEXT.";
function withPrefix(values: Record<string, string>): Record<InsightsKey, string> {
  return Object.fromEntries(
    Object.entries(values).map(([key, value]) => [`${PREFIX}${key}`, value]),
  ) as Record<InsightsKey, string>;
}

