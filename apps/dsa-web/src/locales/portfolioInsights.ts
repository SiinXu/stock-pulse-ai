export type PortfolioInsightsText = Record<
  keyof typeof SOURCE_PORTFOLIO_INSIGHTS_TEXT.zh,
  string
>;

type AdditionalLanguage = Exclude<UiLanguage, 'zh' | 'en'>;

const TRANSLATION_LOADERS = {
  de: () => import('./portfolioInsightsTranslations/de'),
  es: () => import('./portfolioInsightsTranslations/es'),
  fr: () => import('./portfolioInsightsTranslations/fr'),
  id: () => import('./portfolioInsightsTranslations/id'),
  ja: () => import('./portfolioInsightsTranslations/ja'),
  ko: () => import('./portfolioInsightsTranslations/ko'),
  ms: () => import('./portfolioInsightsTranslations/ms'),
  'zh-TW': () => import('./portfolioInsightsTranslations/zh-TW'),
} satisfies Record<AdditionalLanguage, () => Promise<{ default: PortfolioInsightsText }>>;

const translationCache = new Map<AdditionalLanguage, PortfolioInsightsText>();

export function getPortfolioInsightsText(language: UiLanguage): PortfolioInsightsText | null {
  if (language === 'zh' || language === 'en') {
    return SOURCE_PORTFOLIO_INSIGHTS_TEXT[language];
  }
  return translationCache.get(language) ?? null;
}

export async function loadPortfolioInsightsText(language: UiLanguage): Promise<PortfolioInsightsText> {
  if (language === 'zh' || language === 'en') {
    return SOURCE_PORTFOLIO_INSIGHTS_TEXT[language];
  }
  const cached = translationCache.get(language);
  if (cached) return cached;
  const translated = (await TRANSLATION_LOADERS[language]()).default;
  translationCache.set(language, translated);
  return translated;
}
